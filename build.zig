const std = @import("std");

pub fn build(b: *std.Build) !void {
    const src = b.dependency("abseil_src", .{});

    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});

    const abseil_cpp = b.addLibrary(.{
        .name = "abseil",
        .root_module = b.createModule(.{
            .target = target,
            .optimize = optimize,
            .link_libc = true,
            .link_libcpp = true,
        }),
    });
    abseil_cpp.root_module.addCSourceFiles(.{
        .files = abseil_src,
        .root = src.path("absl"),
        .flags = &.{},
        .language = .cpp,
    });
    if (target.result.abi != .msvc) {
        abseil_cpp.root_module.addCSourceFiles(.{
            .files = abseil_not_msvc,
            .root = src.path("absl"),
            .flags = &.{},
            .language = .cpp,
        });
    }
    abseil_cpp.root_module.addIncludePath(src.path(""));

    // Declare include path
    abseil_cpp.installHeadersDirectory(src.path(""), "", .{ .include_extensions = &.{ ".h", ".inc" } });

    b.installArtifact(abseil_cpp);
}

